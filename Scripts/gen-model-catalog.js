#!/usr/bin/env node
// Generate Tinycast/Features/AI/Model/AIModelCatalogData.generated.swift.
//
// Usage: node Scripts/gen-model-catalog.js [api.json]
// Downloads models.dev's catalog when no path is given. Run occasionally, commit the output.
//
// Each API is named by its base URL, because that is all a connection knows about itself; an API
// with no address of its own (`${ACCOUNT}` placeholders, a vendor SDK's default) is either named in
// VENDOR_DEFAULTS or left out, so a connection can never match it by accident.
//
// An API is a `plan` when its id says so or when none of its models has a price: either way nothing
// is billed per token. Local servers are left out, because AIModelCatalog never prices loopback.
"use strict";

const fs = require("fs");
const path = require("path");

const SOURCE = "https://models.dev/api.json";
const OUTPUT = path.join(
  __dirname, "..", "Tinycast", "Features", "AI", "Model", "AIModelCatalogData.generated.swift");

// models.dev leaves these to the vendor's SDK, so it names no address for them.
const VENDOR_DEFAULTS = {
  anthropic: "https://api.anthropic.com",
  cerebras: "https://api.cerebras.ai/v1",
  cohere: "https://api.cohere.ai/compatibility/v1",
  deepinfra: "https://api.deepinfra.com/v1/openai",
  google: "https://generativelanguage.googleapis.com/v1beta/openai",
  groq: "https://api.groq.com/openai/v1",
  mistral: "https://api.mistral.ai/v1",
  openai: "https://api.openai.com/v1",
  perplexity: "https://api.perplexity.ai",
  togetherai: "https://api.together.xyz/v1",
  xai: "https://api.x.ai/v1",
};
const PLAN_ID = /(coding|token|step|code)-plan/;
// The catalog holds about 230 APIs; far fewer is a bad response, not a quiet week.
const MIN_EXPECTED_ROUTES = 100;

async function load(argPath) {
  if (argPath) return JSON.parse(fs.readFileSync(argPath, "utf8"));
  const response = await fetch(SOURCE);
  if (!response.ok) throw new Error(`${SOURCE} -> HTTP ${response.status}`);
  return response.json();
}

function isChatModel(model) {
  const output = model.modalities?.output;
  return !output || output.includes("text");
}

// input/output/cacheRead/cacheWrite/reasoning per million tokens; an absent one is left empty.
function prices(cost) {
  if (typeof cost?.input !== "number" || typeof cost?.output !== "number") return "";
  const reasoning = cost.reasoning === cost.output ? undefined : cost.reasoning;
  return [cost.input, cost.output, cost.cache_read, cost.cache_write, reasoning]
    .map((value) => (typeof value === "number" ? String(value) : ""))
    .join("/");
}

function tiers(cost) {
  return (cost?.tiers ?? [])
    .filter((tier) => tier.tier?.type === "context" && typeof tier.tier.size === "number")
    .map((tier) => [tier.tier.size, prices(tier)])
    .filter(([, tierPrices]) => tierPrices)
    .sort(([left], [right]) => left - right)
    .map(([size, tierPrices]) => `${size}:${tierPrices}`)
    .join(",");
}

function isFree(cost) {
  return !cost || Object.values(cost).every((value) => typeof value !== "number" || value === 0);
}

function clean(text) {
  if (/[\t\n\\"]/.test(text)) throw new Error(`unsafe catalog text: ${JSON.stringify(text)}`);
  return text;
}

async function main() {
  const catalog = await load(process.argv[2]);
  const routes = [];
  const lines = [];
  for (const id of Object.keys(catalog).sort()) {
    const provider = catalog[id];
    const base = VENDOR_DEFAULTS[id] ?? provider.api;
    const models = Object.entries(provider.models ?? {})
      .filter(([, model]) => isChatModel(model))
      .sort(([left], [right]) => (left < right ? -1 : 1));
    if (!base?.startsWith("https://") || base.includes("${") || models.length === 0) continue;
    const plan = PLAN_ID.test(id) || models.every(([, model]) => isFree(model.cost));
    routes.push(`${clean(id)}\t${plan ? "plan" : "api"}\t${clean(base)}`);
    lines.push(`@${clean(id)}`);
    for (const [modelID, model] of models) {
      const window = model.limit?.context > 0 ? model.limit.context : "";
      const priced = plan ? "" : prices(model.cost);
      if (!window && !priced) continue;
      const tiered = plan ? "" : tiers(model.cost);
      lines.push([clean(modelID), window, priced, tiered].join("\t").trimEnd());
    }
  }
  if (routes.length < MIN_EXPECTED_ROUTES) {
    throw new Error(`only ${routes.length} APIs in the catalog; refusing to write`);
  }
  const asOf = new Date().toISOString().slice(0, 10);
  const indented = (rows) => rows.map((row) => `        ${row}`).join("\n");
  fs.writeFileSync(OUTPUT, `// Generated by Scripts/gen-model-catalog.js — do not edit by hand.
// From ${SOURCE} as of ${asOf}.
enum AIModelCatalogData {
    /// One line per API: its id, \`api\` or \`plan\`, and its base URL.
    static let routes = """
${indented(routes)}
        """

    /// \`@\` opens an API; then model id, window, prices per million tokens, and context tiers.
    static let models = """
${indented(lines)}
        """
}
`);
  console.log(`${routes.length} APIs, ${lines.length - routes.length} models`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
